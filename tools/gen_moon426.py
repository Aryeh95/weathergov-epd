#!/usr/bin/env python3
"""Generate the 4.26in layout's moon (renderer426.cpp): NASA's LRO colour map
of the moon (tools/moon/lroc_color_poles_1k.jpg, public domain,
svs.gsfc.nasa.gov/4720) wrapped on the near side of a sphere, as its
brightness, one byte a pixel:

  assets426/moon426.h    MOON426_PX x MOON426_PX, 0 darkest sea .. 255 brightest

The phase is not in the picture: the firmware lights the sphere for the
moment it draws and error-diffuses the result into the panel's greys, so
the moon follows the sky at any phase.

Usage: python tools/gen_moon426.py      (needs pillow and numpy)
"""
import math
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "platformio", "lib", "esp32-weather-epd-assets", "assets426")
PX = 84
SS = 4


def albedo(size, ss=SS):
    src = np.asarray(Image.open(os.path.join(HERE, "moon", "lroc_color_poles_1k.jpg")).convert("L"),
                     dtype=np.float32) / 255.0
    hm, wm = src.shape
    near = src[hm // 8:hm - hm // 8, wm // 4:wm - wm // 4]
    lo, hi = np.percentile(near, 2), np.percentile(near, 80)
    n = size * ss
    ys, xs = np.mgrid[0:n, 0:n]
    x = (xs + 0.5) / n * 2 - 1
    y = (ys + 0.5) / n * 2 - 1
    z = np.sqrt(np.clip(1 - x * x - y * y, 0, 1))
    lat = np.arcsin(np.clip(-y, -1, 1))
    lon = np.arctan2(x, z)
    u = ((lon / (2 * math.pi) + 0.5) * wm).astype(int) % wm
    v = np.clip(((0.5 - lat / math.pi) * hm).astype(int), 0, hm - 1)
    a = np.clip((src[v, u] - lo) / (hi - lo), 0, 1) ** 0.85
    im = Image.fromarray((a * 255).astype(np.uint8), "L").resize((size, size), Image.LANCZOS)
    return np.asarray(im)


def main():
    a = albedo(PX)
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, "moon426.h")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/gen_moon426.py from NASA's LRO map of the moon (public\n"
                "// domain, svs.gsfc.nasa.gov/4720) -- do not edit by hand.\n"
                "// The near side's brightness, %d x %d, row-major, one byte a pixel: 0 the\n"
                "// darkest sea .. 255 the brightest highland. Lit for the phase on the device.\n"
                "#ifndef __MOON426_H__\n#define __MOON426_H__\n\n#include <Arduino.h>\n\n"
                "#define MOON426_PX %d\n\n" % (PX, PX, PX))
        f.write("static const uint8_t MOON426_ALBEDO[%d] PROGMEM = {\n" % (PX * PX))
        flat = a.reshape(-1)
        for i in range(0, len(flat), 20):
            f.write("  " + ",".join("%d" % b for b in flat[i:i + 20]) + ",\n")
        f.write("};\n\n#endif\n")
    print("wrote %s, %d bytes" % (os.path.relpath(path), PX * PX))


if __name__ == "__main__":
    main()
