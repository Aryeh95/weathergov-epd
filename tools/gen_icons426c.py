#!/usr/bin/env python3
"""Condition icons for the 4.26in layout in colour (the reTerminal E1002,
-e seeed_reterminal_e1002_426c): assets426/icons426c.h, at the layout's own
sizes (138 and 48 dots), by the 1600x1200 layout's recipe
(gen_assets709.rework: one solid ink per flat colour, greys as a blue-noise
screen). The artwork is tools/google_icons/ (never committed; see
gen_assets709.py).

    python tools/gen_icons426c.py
"""
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import gen_assets709 as ga  # noqa: E402
import generate_google_preview as gpre  # noqa: E402

SIZES = [138, 48]
out = os.path.join(REPO, "platformio", "lib", "esp32-weather-epd-assets", "assets426", "icons426c.h")
src = os.path.join(TOOLS, "google_icons")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_icons426c.py -- do not edit.\n"
            "// Condition icons for the 4.26in layout in colour, by tools/gen_assets709.py's\n"
            "// recipe, 4 bits a dot (icons_color.h's format).\n"
            "#ifndef __ICONS426C_H__\n#define __ICONS426C_H__\n\n#include <Arduino.h>\n\n")
    codes = sorted(gpre.GOOGLE_MAP)
    for code in codes:
        path = os.path.join(src, gpre.GOOGLE_MAP[code] + ".png")
        if not os.path.exists(path):
            sys.exit("missing %s -- run tools/generate_final_icons.py first, it downloads the set" % path)
        for size in SIZES:
            ga.emit_bytes(f, "ci426_%s_%d" % (code, size), ga.pack4(ga.rework(path, size)))
    f.write("\nstruct Icon426c { const char *code; const uint8_t *px138; const uint8_t *px48; };\n")
    f.write("static const Icon426c ICONS426C[] = {\n")
    for code in codes:
        f.write('  {"%s", ci426_%s_138, ci426_%s_48},\n' % (code, code, code))
    f.write("};\n\n#endif\n")
print("wrote", out)
